// ─────────────────────────────────────────
// frontmatter に affiliateBooks を追加
// ─────────────────────────────────────────
function addAffiliateBooks(content, books) {
  // すでにある場合はスキップ
  if (content.includes('affiliateBooks:')) return null;

  const booksYaml = books.map(b =>
    `  - title: "${b.title}"\n    asin: "${b.asin}"\n    reason: "${b.reason}"`
  ).join('\n');

  // lesson: の後 or --- の前（frontmatter末尾）に挿入
  if (content.match(/^lesson:/m)) {
    return content.replace(/^(lesson:.+)$/m, `$1\naffiliateBooks:\n${booksYaml}`);
  }

  // frontmatter の closing --- の直前に追加
  const fmEnd = content.indexOf('\n---\n', 3);
  if (fmEnd === -1) return null;

  return content.slice(0, fmEnd) + `\naffiliateBooks:\n${booksYaml}` + content.slice(fmEnd);
}

// ─────────────────────────────────────────
// メイン
// ─────────────────────────────────────────
async function main() {
  let added = 0, skipped = 0;

  const dirs = {
    battle:   'src/content/battle',
    leader:   'src/content/leader',
    movie:    'src/content/movie',
    whatif:   'src/content/whatif',
  };

  for (const [cat, dir] of Object.entries(dirs)) {
    const dirPath = path.join(ROOT, dir);
    const files = fs.readdirSync(dirPath).filter(f => f.endsWith('.mdx')).sort();
    console.log(`\n📂 ${cat}`);

    for (const file of files) {
      const slug = file.replace('.mdx', '');
      const books = BOOKS[slug];

      if (!books) {
        console.log(`  ⏭️  ${file} (マッピングなし)`);
        continue;
      }

      const filePath = path.join(ROOT, dir, file);
      const content = fs.readFileSync(filePath, 'utf8');

      const updated = addAffiliateBooks(content, books);
      if (!updated) {
        console.log(`  ⏭️  ${file} (スキップ: 既にあり)`);
        skipped++;
        continue;
      }

      fs.writeFileSync(filePath, updated, 'utf8');
      console.log(`  ✅ ${file}`);
      added++;
    }
  }

  console.log(`\n✅ 完了！ 追加:${added}件 スキップ:${skipped}件`);
}

main().catch(console.error);
